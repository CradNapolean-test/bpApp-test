// Some Lucide icons are aliases: the file only re-exports another icon's file.
function readIconSource(file) {
  const src = fs.readFileSync(path.join(dir, file + '.mjs'), 'utf8');
  const alias = src.match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/);
  return alias ? readIconSource(alias[1]) : src;
}

const out = {};
for (const [name, file] of Object.entries(ICONS)) {
  const src = readIconSource(file);
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\nconst /);
  if (!m) throw new Error('could not read ' + file);
  // The icon node is plain JS data (array of [tag, attributes]); evaluate just that literal.
  const node = new Function('return ' + m[1])();
  out[name] = node.map(([tag, attrs]) => {
    const { key, ...rest } = attrs; // eslint-disable-line no-unused-vars
    return [tag, rest];
  });
}

const body =
  '// GENERATED by scripts/generate-icons.cjs from lucide-react (ISC license). Do not edit by hand.\n' +
  "export type IconNode = [tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse', attrs: Record<string, string | number>][];\n\n" +
  'export const iconData = ' + JSON.stringify(out, null, 2) + ' as const satisfies Record<string, IconNode>;\n\n' +
  'export type IconName = keyof typeof iconData;\n';
fs.writeFileSync(path.join(root, 'apps/mobile/src/components/iconData.ts'), body);
